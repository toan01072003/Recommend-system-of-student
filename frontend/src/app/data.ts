export const avg = (arr: number[]) =>
  (arr.reduce((a, b) => a + b, 0) / arr.length).toFixed(2);

export function scoreCareer(career: ExploreCareer, f: TestFilters): number {
  const map = CAREER_SCORE_MAP[career.id];
  if (!map) return 0;
  let score = 0;
  // Salary (max 20pts)
  if (map.salaryMid >= f.minSalary) score += 20;
  else score += Math.max(0, 20 - (f.minSalary - map.salaryMid) * 2);
  // Education match (15pts)
  if (f.education.length === 0 || f.education.includes(map.education))
    score += 15;
  // Demand (15pts)
  if (f.demand.length === 0 || f.demand.includes(map.demandLevel)) score += 15;
  // Personality (20pts)
  const pMatch = f.personality.filter((p) =>
    map.personalities.includes(p),
  ).length;
  score +=
    f.personality.length === 0
      ? 20
      : Math.round((pMatch / Math.max(f.personality.length, 1)) * 20);
  // Clusters (20pts)
  const cMatch = f.clusters.filter((c) => map.clusters.includes(c)).length;
  score +=
    f.clusters.length === 0
      ? 20
      : Math.round((cMatch / Math.max(f.clusters.length, 1)) * 20);
  // Subjects (10pts)
  const sMatch = f.subjects.filter((s) => map.subjects.includes(s)).length;
  score +=
    f.subjects.length === 0
      ? 10
      : Math.round((sMatch / Math.max(f.subjects.length, 1)) * 10);
  return score;
}
